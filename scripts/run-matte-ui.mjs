// Usage: node scripts/run-matte-ui.mjs "<app url>?debug&noloop"
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright");
const browser = await chromium.launch({ args: ["--enable-unsafe-webgpu", "--enable-features=Vulkan,WebGPU", "--use-angle=swiftshader", "--use-webgpu-adapter=swiftshader"] });
const page = await (await browser.newContext({ viewport: { width: 1180, height: 900 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
await page.goto(process.argv[2]);
await page.waitForFunction(() => window.__rf);
await page.waitForTimeout(600);
const layers = () => page.evaluate(() => JSON.parse(JSON.stringify(window.__rf.ctrl.document.layers)));
await page.getByText("Rect", { exact: true }).click();
await page.getByText("Ellipse", { exact: true }).click();
await page.locator(".tl-label", { hasText: "Rect 1" }).click();
await page.getByLabel("Matte layer").selectOption({ label: "Ellipse 2" });
let l = await layers();
console.log("matte:", JSON.stringify(l[0].matte), "source hidden:", l[1].hidden);
console.log("scene ids:", await page.evaluate(() => window.__rf.ctrl.scene().map((i) => i.id)));
await page.getByRole("group", { name: "Matte mode" }).getByText("Luma", { exact: true }).click();
console.log("mode:", (await layers())[0].matte.mode);
await page.getByText("+ Ellipse").click();
await page.getByText("+ Rect").click();
l = await layers();
console.log("masks:", l[0].masks.map((m) => m.mode));
await page.getByRole("group", { name: "Mask 2 mode" }).getByText("subtract").click();
await page.getByLabel("Invert mask 1").click();
await page.getByLabel("Mask 1 feather").fill("20"); await page.getByLabel("Mask 1 feather").press("Enter");
l = await layers();
console.log("mask1:", JSON.stringify({ ...l[0].masks[0], path: undefined }), "mask2 mode:", l[0].masks[1].mode);
// Edit mask 2 points: node overlay appears on the layer.
await page.getByLabel("Edit points of mask 2").click();
const ov = await page.evaluate(() => window.__rf.ctrl.nodeOverlay());
console.log("mask point overlay nodes:", ov?.nodes.length, "(rect mask = 4)");
await page.getByLabel("Edit points of mask 2").click();
await page.getByLabel("Remove mask 1").click();
console.log("masks after remove:", (await layers())[0].masks.length);
await page.getByText("Undo", { exact: true }).click();
console.log("after undo:", (await layers())[0].masks.length);
await page.getByLabel("Matte layer").selectOption({ label: "None" });
console.log("matte cleared:", (await layers())[0].matte);
console.log("errors:", errors.length ? errors : "none");
await browser.close();
